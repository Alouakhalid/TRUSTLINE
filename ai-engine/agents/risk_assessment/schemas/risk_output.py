"""Output schemas for the TRUSTLINE Risk Assessment Agent structured report."""
from datetime import datetime
from typing import Dict, List, Optional, Any
from pydantic import BaseModel, Field
from .evidence import RiskDomain, EvidenceValidity
from .risk_rules import (
    RiskLevel,
    RiskConfidence,
    EscalationState,
    EscalationDestination,
    TriggeredRuleDetail,
    NonTriggeredRuleDetail
)

class IdentifiedConcern(BaseModel):
    """Specific health concern or data integrity hazard identified by deterministic rules."""
    concern_id: str = Field(..., description="Unique concern identifier e.g. CONCERN-01")
    domain: RiskDomain = Field(..., description="Affected physiological or operational domain")
    severity: RiskLevel = Field(..., description="Categorical risk level of this specific concern")
    title: str = Field(..., description="Clinical title of the detected anomaly or pattern")
    description: str = Field(..., description="Factual evidence-grounded description")
    supporting_evidence_ids: List[str] = Field(default_factory=list, description="IDs of evidence demonstrating concern")
    rule_id: Optional[str] = Field(default=None, description="Deterministic rule establishing this concern")
    uncertainty_note: Optional[str] = Field(default=None, description="Caveats regarding signal quality or telemetry gaps")

class RiskDomainAssessment(BaseModel):
    """Detailed assessment for an individual physiological or operational domain."""
    domain: RiskDomain
    assessment_status: str = Field(..., description="EVALUATED, INSUFFICIENT_DATA, or NOT_EVALUATED")
    risk_level: RiskLevel
    confidence: RiskConfidence
    supporting_evidence_ids: List[str] = Field(default_factory=list)
    triggered_rule_ids: List[str] = Field(default_factory=list)
    limitations: List[str] = Field(default_factory=list)
    explanation: str = Field(..., description="Deterministic factual explanation of domain status")
    requires_human_review: bool = Field(default=False)

class EvidenceSummaryItem(BaseModel):
    """Summarized evidence item highlighting validity and quality state."""
    evidence_id: str
    source_agent: str
    domain: RiskDomain
    metric_name: str
    observed_value_repr: str
    validity_status: EvidenceValidity
    quality_status: Optional[str] = None
    is_confirmed: bool = False
    evidence_classification: str = "CLINICAL_OBSERVATION"
    is_eligible_for_risk: bool = True
    relevance_summary: str

class RecommendedAction(BaseModel):
    """Actionable recommendation for astronaut self-monitoring or flight surgeon review."""
    action_id: str
    action_type: str = Field(..., description="MONITORING, CLINICAL_REVIEW, CMRS_DEPLOYMENT, RECALIBRATION")
    description: str = Field(..., description="Clear operational or medical directive")
    reason: str = Field(..., description="Clinical justification for action")
    supporting_rule_ids: List[str] = Field(default_factory=list)
    supporting_evidence_ids: List[str] = Field(default_factory=list)
    destination: EscalationDestination
    priority: str = Field(default="ROUTINE", description="ROUTINE, URGENT, or CRITICAL")
    requires_human_authorization: bool = Field(default=True)

class ProtocolReference(BaseModel):
    """Authoritative protocol reference underpinning assessment and escalation logic."""
    protocol_id: str
    title: str
    source_organization: str
    version: Optional[str] = None
    section: Optional[str] = None
    relevance_summary: str

class RiskEscalationDetails(BaseModel):
    """Comprehensive escalation decision parameters generated by state machine."""
    state: EscalationState = Field(default=EscalationState.NO_TRIGGER_DETECTED)
    required: bool = Field(default=False)
    urgency_level: str = Field(default="NOMINAL", description="NOMINAL, ELEVATED, URGENT, CRITICAL")
    reason: str = Field(default="No configured escalation rule triggered.")
    supporting_rule_ids: List[str] = Field(default_factory=list)
    destination: EscalationDestination = Field(default=EscalationDestination.FLIGHT_SURGEON)
    immediate_actions: List[str] = Field(default_factory=list)

class AssessmentCoverage(BaseModel):
    """Formal assessment coverage and completeness metrics across supported domains."""
    total_domains: int = Field(default=10, description="Total supported physiological and operational domains")
    evaluated_domains: List[RiskDomain] = Field(default_factory=list, description="Domains with sufficient valid evidence for evaluation")
    unevaluated_domains: List[RiskDomain] = Field(default_factory=list, description="Domains completely unmonitored in this session")
    partially_evaluated_domains: List[RiskDomain] = Field(default_factory=list, description="Domains with degraded or partial telemetry")
    domain_coverage_ratio: float = Field(default=0.0, ge=0.0, le=1.0, description="Fraction of supported domains evaluated (0.0 to 1.0)")
    coverage_status: str = Field(default="INSUFFICIENT", description="COMPLETE (1.0), PARTIAL (0.1-0.9), or INSUFFICIENT (0.0)")
    unavailable_domain_reasons: Dict[str, str] = Field(default_factory=dict, description="Domain-specific factual reasons for omission")

class ProtectiveFactorItem(BaseModel):
    """Formally audited protective factor grounded in documented evidence and reference criteria."""
    factor_id: str = Field(..., description="Unique protective factor identifier e.g. PROT-CARDIO-01")
    domain: RiskDomain = Field(..., description="Associated physiological or operational domain")
    source_agent: str = Field(..., description="Originating agent providing supporting telemetry or record")
    supporting_evidence_ids: List[str] = Field(default_factory=list, description="Specific empirical evidence IDs demonstrating normality")
    validity_status: EvidenceValidity = Field(default=EvidenceValidity.VALID, description="Verified validity state of supporting data")
    applicable_criterion: str = Field(..., description="Documented reference standard or protocol threshold satisfied")
    explanation: str = Field(..., description="Factual justification for protective classification")
    factor_type: str = Field(default="NOMINAL_OBSERVATION", description="NOMINAL_OBSERVATION or PROTECTIVE_FACTOR")

class RiskAssessmentOutput(BaseModel):
    """Final structured report produced by Risk Assessment Agent for Supervisor."""
    assessment_id: str
    astronaut_id: str
    session_id: str
    assessment_timestamp: datetime = Field(default_factory=datetime.utcnow)
    assessment_status: str = Field(default="COMPLETED", description="COMPLETED, PARTIALLY_COMPLETED, INSUFFICIENT_DATA, or FAILED")
    evaluated_domains_risk: RiskLevel = Field(default=RiskLevel.UNKNOWN, description="Risk level across evaluated domains only")
    overall_risk: RiskLevel = Field(default=RiskLevel.UNKNOWN, description="System-wide composite risk factoring coverage completeness")
    overall_confidence: RiskConfidence = Field(default=RiskConfidence.UNDETERMINED)
    coverage: Optional[AssessmentCoverage] = Field(default=None, description="Quantified domain coverage report")
    risk_domains: List[RiskDomainAssessment] = Field(default_factory=list)
    identified_concerns: List[IdentifiedConcern] = Field(default_factory=list)
    evidence_summary: List[EvidenceSummaryItem] = Field(default_factory=list)
    triggered_rules: List[TriggeredRuleDetail] = Field(default_factory=list)
    non_triggered_rules: List[NonTriggeredRuleDetail] = Field(default_factory=list)
    uncertainties: List[str] = Field(default_factory=list)
    missing_information: List[str] = Field(default_factory=list)
    nominal_observation_details: List[ProtectiveFactorItem] = Field(default_factory=list, description="Audited nominal observations within normal limits")
    nominal_observations: List[str] = Field(default_factory=list, description="String representations of nominal observations")
    protective_factor_details: List[ProtectiveFactorItem] = Field(default_factory=list, description="Audited protective factors")
    protective_factors: List[str] = Field(default_factory=list, description="String representations for backward compatibility")
    escalation: RiskEscalationDetails = Field(default_factory=RiskEscalationDetails)
    recommended_actions: List[RecommendedAction] = Field(default_factory=list)
    protocol_references: List[ProtocolReference] = Field(default_factory=list)
    requires_human_review: bool = Field(default=False)
    processing_metadata: Dict[str, Any] = Field(default_factory=dict)
    llm_explanation: Optional[str] = Field(default=None)
    llm_status: str = Field(default="LLM_SKIPPED")
